"""One-off script that built eval/labeled_reviews.csv.

Not part of the runtime pipeline — kept for reproducibility/audit: it
shows exactly which real reviews were hand-labeled and why, rather
than the labels appearing from nowhere. Labels themselves were
assigned by reading each review's content (see LABELS below), not
generated by any model.
"""
import pandas as pd

from app_review_agent.config import REVIEWS_CSV_PATH

# review_id -> hand-assigned ground-truth category.
# Picked by keyword-assisted search over data/reviews.csv, then verified
# by reading the full review text. Note: this app (WhatsApp) is free with
# no in-app purchases, so genuine "billing" complaints are almost
# nonexistent in the corpus — only one loose match ("ads") was found.
# That scarcity is itself a real finding, documented in eval/README.md
# rather than papered over with invented examples.
LABELS = {
    # crash: fails to open/run/install
    "bf7be983-000b-430f-9c14-55999b1ea41f": "crash",
    "ef47f298-2155-46a8-a411-b44c0f7b0275": "crash",
    "6ca80201-df3e-492d-ae65-e83952665bfb": "crash",
    "ed2ccafe-c00b-4af3-9c57-fa29b460d6a3": "crash",
    "61d4ecc3-a2b9-47f5-a46f-b213852c8e8d": "crash",
    # ux: friction/annoyance/design complaints, app still basically works
    "62988c01-d5e0-41a1-8c6f-7a6995fb2c05": "ux",
    "c9cedcf4-642b-413e-820f-c7db5adb086e": "ux",
    "086412d2-91fa-4e34-b386-718f5e600f92": "ux",
    "4a0b89e4-c3cc-4d07-8d3b-08789c85c6bf": "ux",
    # feature_request: explicitly asks for new/changed behavior
    "81270706-6240-4638-9757-98459c70962d": "feature_request",
    "622f457b-1491-41c9-a095-0cdca1f46151": "feature_request",
    "34dce9a9-897a-4c85-9474-3c5de829443a": "feature_request",
    "c6b6f0fb-93d6-43ce-a656-881171b08bf2": "feature_request",
    # praise: positive, no specific complaint
    "23e50358-8015-40e4-8311-ee47dc69222b": "praise",
    "adb7ba83-444e-4be9-b166-a73ce7dd0e1b": "praise",
    "a44843b7-d550-4764-ae45-712789ecc41a": "praise",
    "ba085b88-2e92-4809-9391-c781a271251e": "praise",
    "c9208ca6-d84e-40e7-bdc1-4131be16b5a7": "praise",
    # billing: only loose match found in this corpus (see note above)
    "31aa1953-4605-4001-84d7-406925135688": "billing",
}


def main() -> None:
    df = pd.read_csv(REVIEWS_CSV_PATH)
    labeled = df[df["review_id"].isin(LABELS)].copy()
    labeled["label"] = labeled["review_id"].map(LABELS)
    labeled = labeled[["review_id", "content", "rating", "app_version", "at", "label"]]
    labeled.to_csv("eval/labeled_reviews.csv", index=False)
    print(f"Wrote {len(labeled)} labeled reviews to eval/labeled_reviews.csv")
    print(labeled["label"].value_counts())


if __name__ == "__main__":
    main()
